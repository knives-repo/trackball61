static void oled_write_raw_shift_P(const char *data, uint16_t size, int8_t x_shift) {
    static char buffer[ANIM_SIZE];
    
    memset(buffer, 0, size);

    for (uint16_t i = 0; i < size; i++) {
        // Shift the index (Horizontal move)
        // One 'i' represents one vertical column of 8 pixels
        int16_t target_idx = i + x_shift;

        if (target_idx >= 0 && target_idx < size) {
            buffer[target_idx] = pgm_read_byte(&data[i]);
        }
    }
    oled_write_raw(buffer, size);
}

static void update_kodama_drift(void) {
    if (timer_elapsed32(drift_timer) > 60000) {  // every 60s
        drift_timer = timer_read32();
        kodama_pixel_drift = (rand() % 3) - 1;  // -1,0,+1
    }
}

void animate_kodama(void) {
    if (timer_elapsed32(anim_timer1) > ANIM_FRAME_DURATION) {
        anim_timer1 = timer_read32();
        
        oled_set_cursor(0, 5); // Set cursor properly on screen for Kodama
        update_kodama_drift();
        
        if (get_current_wpm() <= MIN_WALK_SPEED) {
            // Sequence: 10 (sit 2) + 1 (sit[0]) + 40 (still) + 1 (still) + 10 (sit 1) = 62
            current_frame1 = (current_frame1 + 1) % 62;

            if (current_frame1 < 10) {
                // Frames 0–9: Sit (second time)
                oled_write_raw_shift_P(sit[current_frame1], ANIM_SIZE, kodama_pixel_drift);
            }
            else if (current_frame1 == 10) {
                // Frame 10: sit[0]
                oled_write_raw_shift_P(sit[0], ANIM_SIZE, kodama_pixel_drift);
            }
            else if (current_frame1 < 52) {
                // Frames 11–51: still (41 frames)
                oled_write_raw_shift_P(still[0], ANIM_SIZE, kodama_pixel_drift);
            }
            else {
                // Frames 52–61: Sit (first time)
                oled_write_raw_shift_P(sit[current_frame1 - 52], ANIM_SIZE, kodama_pixel_drift);
            }
        }
        else {
            current_frame1 = (current_frame1 + 1) % 4;
            oled_write_raw_shift_P(walk[current_frame1], ANIM_SIZE, kodama_pixel_drift);
        }
    }
}